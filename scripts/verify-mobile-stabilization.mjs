import { readFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=rel=>readFile(path.join(root,rel),'utf8');
const must=(value,message)=>{if(!value)throw new Error(message)};

const globalJs=await read('public/assets/js/fmb-news-mobile-global.js');
const homeJs=await read('public/assets/js/fmb-news-mobile-home.js');
const materialCss=await read('public/assets/css/fmb-news-mobile-material-polish.css');
const navCss=await read('public/assets/css/fmb-news-mobile-navigation-lock.css');
const pwaJs=await read('public/assets/js/fmb-news-pwa.js');
const mobilePass=await read('scripts/hardfix-mobile-first-site.mjs');

for(const duplicate of ['WEATHER_KEY','weatherLabels','fetchWeather(','geocode(','weatherSheet(','data-fmb-local-time','data-fmb-weather-button']){
  must(!globalJs.includes(duplicate),`Shared mobile shell must not own Home clock/weather runtime: ${duplicate}`);
}
must(!globalJs.includes('.style.setProperty'),'Shared mobile shell must not paint presentation with inline style.setProperty');
must(!globalJs.includes('fmb-approved-bottom-nav'),'Retired pre-redesign bottom navigation must stay removed');
must(globalJs.includes('fmb-editorial-mobile-dock'),'New editorial mobile dock must be generated by the shared shell runtime');
must(globalJs.includes('aria-label="FMB News quick navigation"'),'Editorial dock must expose a navigation label');
// The dock is the single primary mobile navigation. It used to be one of three:
// a section rail under the app bar repeated four of these five items, and an
// app-bar hamburger opened the same panel as the dock's Menu. Both are gone, so
// this asserts the dock's structure directly and asserts the duplicates stay
// removed, rather than asserting the rail's structure as it did before.
must(globalJs.includes("['news','/news/','Home','home']")&&globalJs.includes("['world','/news/world/','World','world']")&&globalJs.includes("['sports','/news/sports/','Sports','sports']")&&globalJs.includes("['brief','/news/fmb-brief/','Briefing','brief']"),'Bottom dock must carry Home, World, Sports and Briefing');
must(globalJs.includes('data-fmb-dock-menu'),'Bottom dock must expose the Menu action');
// Matched against the generated markup, not the file text, so the comment that
// records why the rail was removed does not itself trip the guard.
must(!globalJs.includes('class="fmb-mobile-product-rail"'),'The duplicated mobile section rail must stay removed; the dock is the single primary navigation');
must(!globalJs.includes('data-fmb-shell-menu>')&&!globalJs.includes('data-fmb-shell-menu '),'The app-bar hamburger must stay removed; the dock Menu opens the same panel');
must(globalJs.includes('aria-haspopup="dialog"')&&globalJs.includes("aria-expanded"),'The dock Menu must expose its dialog relationship and open state');
must(globalJs.includes("e.key==='Escape'")&&globalJs.includes('opener.focus({preventScroll:true})'),'Shared mobile action sheet must support Escape and restore focus');
must(globalJs.includes('focusableSelector')&&globalJs.includes("e.key!=='Tab'"),'Shared mobile action sheet must trap keyboard focus');

must(globalJs.includes('fmb-mobile-shell-actions fmb-mobile-shell-search'),'Shared masthead must contain Search');
must(!globalJs.includes('data-fmb-shell-account'),'No standalone profile/account control may exist in the mobile masthead');
must(globalJs.includes('data-fmb-open-account')&&globalJs.includes("svg('account')"),'Your FMB profile must live inside the menu');
must(globalJs.includes('FMB NEWS<span class="fmb-mobile-brand-dot">.</span>'),'Mobile masthead must use the new FMB NEWS. wordmark');
must(globalJs.includes("const ticker=$('.fmb-app-top-ticker')")&&globalJs.includes('if(ticker)shell.append(ticker)'),'Home Headlines must remain inside the sticky FMB shell');

for(const pht of ["timeZone:'Asia/Manila'",'phtHour(',' PHT'])must(homeJs.includes(pht),`Home must keep Philippine Standard Time authoritative: ${pht}`);
must(homeJs.includes("prefers-reduced-motion: reduce")&&homeJs.includes('clearInterval(sloganTimer)')&&homeJs.includes('reducedMotion.matches'),'Home slogan motion must stop when reduced motion is requested');
must(homeJs.includes("e.key==='Escape'")&&homeJs.includes('opener.focus({preventScroll:true})'),'Weather dialog must support Escape and restore focus');

for(const token of ['font-size:8.8px!important','font-size:8.2px!important','font-size:9px!important','font-size:9.5px!important','min-width:44px!important']){
  must(materialCss.includes(token),`Critical mobile readability/touch-target override missing: ${token}`);
}

const routePolish={
  archive:['fmb-mobile-route-archive .archive-row','border-radius:0!important'],
  world:['fmb-mobile-route-world .country-card','font-size:13px!important'],
  explainer:['fmb-mobile-route-explainer .explained-item','font-size:15px!important'],
  brief:['fmb-mobile-route-brief .brief-issue','font-size:18px!important'],
  horoscope:['fmb-mobile-route-horoscope .fmb-zodiac-grid button','border-radius:var(--fmb-screen-radius)!important'],
  crossword:['fmb-mobile-route-crossword .fmb-crossword-toolbar button','min-height:44px!important'],
  about:['fmb-mobile-route-about .fmb-about-method-list li','font-size:14px!important'],
  article:['fmb-mobile-route-article .article-body p','font-size:17.5px!important']
};
for(const[route,tokens]of Object.entries(routePolish))for(const token of tokens)must(materialCss.includes(token),`All-screen mobile polish missing for ${route}: ${token}`);
// This used to require a compact .fmb-mobile-product-rail rule for internal
// screens. That rail is no longer built on any route, so a rule for it proves
// nothing about what a reader sees; the dock's own presence and geometry are
// asserted in the browser suite, where they can be measured.
must(materialCss.includes('--fmb-screen-gutter:16px'),'Internal routes must share the 16px mobile spacing system');

for(const token of [
  'position:sticky!important','grid-column:3!important','.fmb-mobile-app-shell>.fmb-app-top-ticker',
  'position:relative!important','top:auto!important','.fmb-install-card{display:none!important',
  'grid-template-columns:repeat(5,minmax(64px,1fr))','--fmb-mobile-red:#D71920',
  '.fmb-editorial-mobile-dock','position:fixed!important','bottom:0!important','fmb-mobile-brand-dot'
])must(navCss.includes(token),`Shared navigation/editorial lock missing: ${token}`);
must(!navCss.includes('#f2d17a'),'Superseded gold mobile highlight returned in final navigation lock');
must(!navCss.includes('#630661'),'Superseded plum mobile highlight returned in final navigation lock');

must(!pwaJs.includes('.fmb-pwa-install{'),'PWA runtime must not create a second floating install button');
must(pwaJs.includes("document.addEventListener('fmb:install-request',requestInstall)"),'PWA install sheet must be triggered from the menu flow');
must(pwaJs.includes('Safari controls the Apple system action'),'iOS install guidance must make Safari ownership explicit');

must(mobilePass.includes("const MOBILE_SYSTEM_FILE='fmb-news-mobile-system.css'"),'Mobile CSS must ship through the single system bundle');
must(mobilePass.includes("createHash('sha256')"),'Mobile CSS system bundle must be content-versioned');
must(mobilePass.includes('MOBILE_SYSTEM_SHEETS'),'Mobile CSS cascade order must remain explicit and verifiable');
must(mobilePass.includes("'fmb-news-mobile-navigation-lock.css'"),'Shared navigation lock must remain bundled last');
must(mobilePass.includes('content="#0A0A0A"'),'PWA/browser chrome must use newsroom black');

console.log('Mobile stabilization contracts passed: one PHT runtime, FMB NEWS. masthead over a wordmark-and-search app bar, story-led Home, the five-item editorial dock as the single primary navigation with no section rail or hamburger duplicating it, accessible menu sheets, reduced motion, and route-wide readability.');